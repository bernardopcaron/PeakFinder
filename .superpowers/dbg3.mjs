import { chromium } from "@playwright/test";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
p.on("console", (m) => { if (m.type() === "error") console.log("console:", m.text().slice(0, 200)); });
await p.goto("http://localhost:3000/areas/pedra-do-bau");
const v = p.getByTestId("visualizador-3d");
await v.scrollIntoViewIfNeeded();
await p.waitForSelector('[data-testid="visualizador-3d"][data-estado="pronto"]', { timeout: 30000 });
console.log(await v.getAttribute("data-camera"));
const c = await v.locator("canvas").boundingBox();
console.log(c);
const cx = c.x + c.width / 2, cy = c.y + c.height / 2;
console.log(await p.evaluate(([x, y]) => { const e = document.elementFromPoint(x, y); return e && (e.tagName + "." + e.className).slice(0, 120); }, [cx, cy]));
await p.evaluate(() => { window.__ev = []; for (const t of ["pointerdown","pointermove","pointerup","pointercancel"]) document.addEventListener(t, (e) => window.__ev.push(t + ":" + e.target.tagName), true); });
await p.mouse.move(cx, cy); await p.mouse.down(); await p.mouse.move(cx + 120, cy + 30, { steps: 8 }); await p.mouse.up();
await p.waitForTimeout(500);
console.log(await v.getAttribute("data-camera"));
console.log((await p.evaluate(() => window.__ev)).join(" ").slice(0, 300));
await p.screenshot({ path: "/tmp/shots/3d.png" });
await b.close();
